import sys
# 16x16 pixel cat. '#' = fur, 'e' = eye, 'n' = nose, '.' = empty.
# Run: python3 scripts/icon.py data/icons
CAT = [  # just the cat, rounder cheeks
    "................",
    "................",
    "..#..........#..",
    "..##........##..",
    "..###......###..",
    "..############..",
    "..############..",
    ".###ee####ee###.",
    ".###ee####ee###.",
    ".##############.",
    ".######nn######.",
    ".##############.",
    "..############..",
    "....########....",
    "................",
    "................",
]
assert all(len(r) == 16 for r in CAT) and len(CAT) == 16
for r in CAT:
    assert r == r[::-1], r  # symmetric

def rects(chars, scale=1, ox=0, oy=0):
    """Merge horizontal runs into rects."""
    out = []
    for y, row in enumerate(CAT):
        x = 0
        while x < 16:
            if row[x] in chars:
                x0 = x
                while x < 16 and row[x] in chars:
                    x += 1
                out.append((ox + x0 * scale, oy + y * scale, (x - x0) * scale, scale))
            else:
                x += 1
    return out

def svg_rects(rs, fill):
    return "\n".join(f'  <rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{fill}"/>' for x, y, w, h in rs)

out = sys.argv[1]
# symbolic: fur only (eyes, nose, mouth stay transparent)
sym = f'''<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" shape-rendering="crispEdges">
  <!-- TokenBar: pixel cat. Symbolic: recoloured by the panel. Generated by scripts/icon.py -->
{svg_rects(rects("#"), "#2e3436")}
</svg>
'''
# colour app icon: 128px tile, cat at 6px per pixel, centred
S, O = 6, (128 - 16 * 6) // 2
col = f'''<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#6a4bc4"/>
      <stop offset="1" stop-color="#2f4a9e"/>
    </linearGradient>
  </defs>
  <rect x="8" y="8" width="112" height="112" rx="26" fill="url(#bg)"/>
  <g shape-rendering="crispEdges">
{svg_rects(rects("#", S, O, O), "#ffffff")}
{svg_rects(rects("e", S, O, O), "#2bd4a4")}
{svg_rects(rects("n", S, O, O), "#ff4d7a")}
  </g>
</svg>
'''
# panel: 20px tile with the 16px cat centred (2px of background around it), pixel-aligned
P = 2
panel = f'''<svg xmlns="http://www.w3.org/2000/svg" width="20" height="20" viewBox="0 0 20 20">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#6a4bc4"/>
      <stop offset="1" stop-color="#2f4a9e"/>
    </linearGradient>
  </defs>
  <rect width="20" height="20" rx="4.5" fill="url(#bg)"/>
  <g shape-rendering="crispEdges">
{svg_rects(rects("#", 1, P, P), "#ffffff")}
{svg_rects(rects("e", 1, P, P), "#2bd4a4")}
{svg_rects(rects("n", 1, P, P), "#ff4d7a")}
  </g>
</svg>
'''
open(f"{out}/io.github.eduardafranca.TokenBar-panel.svg", "w").write(panel)
open(f"{out}/io.github.eduardafranca.TokenBar-symbolic.svg", "w").write(sym)
open(f"{out}/io.github.eduardafranca.TokenBar.svg", "w").write(col)
print("ok")
